def _own(name: str) -> str:
    if name in DESC:
        return DESC[name]
    for k, v in DESC.items():
        if k.endswith("*") and name.startswith(k[:-1]):
            return v
    return ""


@lru_cache(maxsize=1)
def _spec_patterns() -> list[tuple[re.Pattern, str]]:
    return [(re.compile("^" + re.escape(p).replace("%", ".*") + "$", re.S), d)
            for p, d in specialty_desc.DESC.items() if d]


@lru_cache(maxsize=4096)
def describe(name: str) -> str:
    """届出名称の説明（無ければ空文字）。"""
    d = _own(name)
    if d:
        return d
    for rx, d in _spec_patterns():
        if rx.match(name):
            return d
    return dict.get(shika_kijun.DESC, name, "")
